import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
// @ts-expect-error plain JavaScript module of the supervisor
import { coordinatorAddress, migrateZ2mData, validCoordinator, z2mEnv } from '../supervisor/z2m.mjs';

const dirs: string[] = [];
const tmp = () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'synbee-z2m-'));
  dirs.push(d);
  return d;
};
afterEach(() => {
  for (const d of dirs.splice(0)) fs.rmSync(d, { recursive: true, force: true });
});

function fakeZ2mData(dir: string) {
  fs.mkdirSync(path.join(dir, 'external_converters'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'configuration.yaml'), 'advanced:\n  network_key: [1, 2, 3]\n');
  fs.writeFileSync(path.join(dir, 'coordinator_backup.json'), '{"network_key":"secret"}');
  fs.writeFileSync(path.join(dir, 'external_converters', 'x.mjs'), 'export default {}');
}

describe('Zigbee2MQTT settings', () => {
  it('points at the SLZB-06MU over TCP with the ember adapter and no flow control', () => {
    const env = z2mEnv({ dataDir: '/private/z2m', coordinator: '192.168.1.50:6638', mqttPort: 18830, mqttPassword: 'pw' });
    expect(env).toMatchObject({
      ZIGBEE2MQTT_DATA: '/private/z2m',
      ZIGBEE2MQTT_CONFIG_SERIAL_PORT: 'tcp://192.168.1.50:6638',
      ZIGBEE2MQTT_CONFIG_SERIAL_ADAPTER: 'ember',
      ZIGBEE2MQTT_CONFIG_SERIAL_RTSCTS: 'false',
      ZIGBEE2MQTT_CONFIG_MQTT_SERVER: 'mqtt://127.0.0.1:18830',
      ZIGBEE2MQTT_CONFIG_FRONTEND_ENABLED: 'false',
      Z2M_ONBOARD_NO_SERVER: '1',
    });
    // The network key is generated by Zigbee2MQTT in its private folder, never set by the hub.
    expect(Object.keys(env).some((k) => k.includes('NETWORK_KEY'))).toBe(false);
  });

  it('prefers the address saved by the replace step, and ignores bad values', () => {
    const secrets = tmp();
    expect(coordinatorAddress(secrets, '')).toBe('');
    expect(coordinatorAddress(secrets, 'not an address')).toBe('');
    expect(coordinatorAddress(secrets, '192.168.1.50:6638')).toBe('192.168.1.50:6638');
    fs.writeFileSync(path.join(secrets, 'coordinator'), '192.168.1.141:6638\n');
    expect(coordinatorAddress(secrets, '192.168.1.50:6638')).toBe('192.168.1.141:6638');
    fs.writeFileSync(path.join(secrets, 'coordinator'), 'garbage');
    expect(coordinatorAddress(secrets, '192.168.1.50:6638')).toBe('192.168.1.50:6638');
    expect(validCoordinator('slzb-06mu.lan:6638')).toBe(true);
    expect(validCoordinator('host:70000')).toBe(false);
  });
});

describe('moving Zigbee2MQTT data out of the share', () => {
  it('copies, checks and deletes the share copy', () => {
    const share = path.join(tmp(), 'zigbee2mqtt');
    const priv = path.join(tmp(), 'zigbee2mqtt');
    fakeZ2mData(share);
    expect(migrateZ2mData(share, priv)).toMatch(/^moved/);
    expect(fs.existsSync(share)).toBe(false);
    expect(fs.readFileSync(path.join(priv, 'coordinator_backup.json'), 'utf8')).toContain('secret');
    expect(fs.statSync(priv).mode & 0o777).toBe(0o700);
    expect(fs.existsSync(`${priv}.moving`)).toBe(false);
  });

  it('is safe to repeat, and finishes an interrupted move', () => {
    const share = path.join(tmp(), 'zigbee2mqtt');
    const priv = path.join(tmp(), 'zigbee2mqtt');
    fakeZ2mData(share);
    // Interrupted while copying: a partial staging folder is thrown away and the copy starts again.
    fs.mkdirSync(`${priv}.moving`);
    fs.writeFileSync(`${priv}.moving/partial`, 'x');
    expect(migrateZ2mData(share, priv)).toMatch(/^moved/);
    expect(fs.existsSync(path.join(priv, 'partial'))).toBe(false);
    // Repeated: nothing left to move.
    expect(migrateZ2mData(share, priv)).toBe('nothing to move');
    // Interrupted after the rename, before deleting the share copy.
    fakeZ2mData(share);
    expect(migrateZ2mData(share, priv)).toMatch(/^moved/);
    expect(fs.existsSync(share)).toBe(false);
  });

  it('refuses when both copies exist and differ, keeping both', () => {
    const share = path.join(tmp(), 'zigbee2mqtt');
    const priv = path.join(tmp(), 'zigbee2mqtt');
    fakeZ2mData(share);
    fakeZ2mData(priv);
    fs.writeFileSync(path.join(priv, 'state.json'), '{}');
    expect(() => migrateZ2mData(share, priv)).toThrow(/differ/);
    expect(fs.existsSync(share)).toBe(true);
    expect(fs.existsSync(priv)).toBe(true);
  });
});
