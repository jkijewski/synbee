// Zigbee2MQTT settings and data-folder handling for the supervisor. Kept apart so it can be tested.
import fs from 'node:fs';
import path from 'node:path';

/** Zigbee channel for a new network: 25 sits above Wi-Fi channel 11, away from the usual 1, 6 and 11. */
export const ZIGBEE_CHANNEL = 25;

const HOST_PORT = /^(?:[A-Za-z0-9.-]{1,253}):(\d{1,5})$/;

export function validCoordinator(value) {
  const m = HOST_PORT.exec(value ?? '');
  return Boolean(m) && Number(m[1]) >= 1 && Number(m[1]) <= 65535;
}

/**
 * The coordinator address in use: one saved by the hub's "replace coordinator" step wins over the
 * package wizard's. Returns '' when none is set, in which case Zigbee2MQTT is not started.
 */
export function coordinatorAddress(secretsDir, fromWizard, network = 1) {
  const file = path.join(secretsDir, `coordinator${suffix(network)}`);
  try {
    const saved = fs.readFileSync(file, 'utf8').trim();
    if (validCoordinator(saved)) return saved;
  } catch {
    // Not replaced through the hub.
  }
  if (network !== 1) return ''; // only the first gateway comes from the install wizard
  const wizard = (fromWizard ?? '').trim();
  return validCoordinator(wizard) ? wizard : '';
}

export const ADAPTERS = ['ember', 'zstack', 'deconz', 'zigate', 'zboss'];

/**
 * Several gateways (0023): each is its own Zigbee network with its own Zigbee2MQTT. The first keeps the names it always
 * had (coordinator, gateway.json, zigbee2mqtt/, MQTT base topic zigbee2mqtt); gateway n adds "-n" to each.
 */
export const suffix = (network) => (network === 1 ? '' : `-${network}`);
export const baseTopic = (network) => `zigbee2mqtt${suffix(network)}`;

/** The gateways the hub has: networks.json in the private folder, written by the hub; always at least the first. */
export function networkIds(secretsDir) {
  let saved = [];
  try {
    saved = JSON.parse(fs.readFileSync(path.join(secretsDir, 'networks.json'), 'utf8'));
  } catch {
    // Only the first gateway.
  }
  const ids = Array.isArray(saved) ? saved.map((n) => n?.id).filter((id) => Number.isInteger(id) && id >= 1 && id <= 9) : [];
  return [...new Set([1, ...ids])].sort((a, b) => a - b);
}

/**
 * Gateway settings saved by the hub's Gateway page (gateway.json in the private folder): adapter type, flow control
 * and Zigbee channel. Missing or bad values fall back to the SLZB-06MU defaults.
 */
export function gatewaySettings(secretsDir, network = 1) {
  let saved = {};
  try {
    saved = JSON.parse(fs.readFileSync(path.join(secretsDir, `gateway${suffix(network)}.json`), 'utf8'));
  } catch {
    // Defaults.
  }
  return {
    adapter: ADAPTERS.includes(saved.adapter) ? saved.adapter : 'ember',
    rtscts: saved.rtscts === true,
    channel: Number.isInteger(saved.channel) && saved.channel >= 11 && saved.channel <= 26 ? saved.channel : network === 1 ? ZIGBEE_CHANNEL : 20,
  };
}

/**
 * Environment for Zigbee2MQTT. Everything SynBee depends on is set here rather than in configuration.yaml,
 * so it applies on every start; Zigbee2MQTT writes it into its configuration file itself. The network key,
 * PAN ID and extended PAN ID are generated by Zigbee2MQTT at its first start and stay in its private data folder.
 */
export function z2mEnv({ dataDir, coordinator, mqttPort, mqttPassword, gateway = { adapter: 'ember', rtscts: false, channel: ZIGBEE_CHANNEL }, network = 1 }) {
  return {
    ZIGBEE2MQTT_DATA: dataDir,
    // No onboarding web page: SynBee is the interface.
    Z2M_ONBOARD_NO_SERVER: '1',
    // Zigbee2MQTT asks git for its version and rebuilds itself on a mismatch; there is no repo here.
    GIT_DIR: path.join(dataDir, '.no-git'),
    ZIGBEE2MQTT_CONFIG_MQTT_SERVER: `mqtt://127.0.0.1:${mqttPort}`,
    ZIGBEE2MQTT_CONFIG_MQTT_USER: 'hub',
    ZIGBEE2MQTT_CONFIG_MQTT_PASSWORD: mqttPassword,
    ZIGBEE2MQTT_CONFIG_MQTT_BASE_TOPIC: baseTopic(network),
    // Two Zigbee2MQTT on one broker need different client ids.
    ZIGBEE2MQTT_CONFIG_MQTT_CLIENT_ID: `synbee-z2m${suffix(network)}`,
    ZIGBEE2MQTT_CONFIG_SERIAL_PORT: `tcp://${coordinator}`,
    ZIGBEE2MQTT_CONFIG_SERIAL_ADAPTER: gateway.adapter,
    // Network coordinators have no flow control lines; off unless set on the Gateway page.
    ZIGBEE2MQTT_CONFIG_SERIAL_RTSCTS: String(gateway.rtscts),
    ZIGBEE2MQTT_CONFIG_ADVANCED_CHANNEL: String(gateway.channel),
    ZIGBEE2MQTT_CONFIG_ADVANCED_LOG_OUTPUT: '["console"]',
    ZIGBEE2MQTT_CONFIG_ADVANCED_LAST_SEEN: 'ISO_8601',
    ZIGBEE2MQTT_CONFIG_FRONTEND_ENABLED: 'false',
    ZIGBEE2MQTT_CONFIG_HOMEASSISTANT_ENABLED: 'false',
    ZIGBEE2MQTT_CONFIG_AVAILABILITY_ENABLED: 'true',
    // The hub checks for releases itself (0016); Zigbee2MQTT must not reach out for OTA index updates on its own.
    ZIGBEE2MQTT_CONFIG_OTA_DISABLE_AUTOMATIC_UPDATE_CHECK: 'true',
  };
}

function listTree(root) {
  const out = new Map();
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) out.set(path.relative(root, full), fs.readFileSync(full));
    }
  };
  walk(root);
  return out;
}

function sameTree(a, b) {
  const left = listTree(a);
  const right = listTree(b);
  if (left.size !== right.size) return false;
  for (const [name, content] of left) {
    const other = right.get(name);
    if (!other || !content.equals(other)) return false;
  }
  return true;
}

/**
 * Moves Zigbee2MQTT's data from the shared folder (builds before 0.2.0) into the private folder (0006).
 * Copy, check, then delete, because the two folders can be on different btrfs subvolumes. Safe to run again after
 * an interruption at any point. Returns a short description of what it did, or throws if the copies disagree,
 * in which case Zigbee2MQTT must not start.
 */
export function migrateZ2mData(fromDir, toDir) {
  if (path.resolve(fromDir) === path.resolve(toDir) || !fs.existsSync(fromDir)) return 'nothing to move';
  const staging = `${toDir}.moving`;
  if (!fs.existsSync(toDir)) {
    fs.rmSync(staging, { recursive: true, force: true });
    fs.cpSync(fromDir, staging, { recursive: true, preserveTimestamps: true });
    if (!sameTree(fromDir, staging)) throw new Error('The copy of the Zigbee2MQTT data differs from the original');
    fs.chmodSync(staging, 0o700);
    // Same parent folder, so this rename is on one file system.
    fs.renameSync(staging, toDir);
  } else if (!sameTree(fromDir, toDir)) {
    throw new Error(`Zigbee2MQTT data exists both in ${fromDir} and ${toDir}, and they differ; leaving both for the owner`);
  }
  fs.rmSync(fromDir, { recursive: true, force: true });
  return `moved ${fromDir} to ${toDir}`;
}

/**
 * Puts a restored backup in place before Zigbee2MQTT starts (0007). The hub unpacks a downloaded backup into
 * `<data>.restore`; the current data is kept as `<data>.before-restore-<time>`, never deleted. Returns a description,
 * or '' when there was nothing to restore.
 */
export function applyPendingRestore(dataDir, now = new Date()) {
  const staged = `${dataDir}.restore`;
  if (!fs.existsSync(path.join(staged, 'coordinator_backup.json'))) return '';
  let kept = '';
  if (fs.existsSync(dataDir)) {
    kept = `${dataDir}.before-restore-${now.toISOString().replace(/[:.]/g, '-')}`;
    fs.renameSync(dataDir, kept);
  }
  fs.renameSync(staged, dataDir);
  fs.chmodSync(dataDir, 0o700);
  return kept ? `restored a downloaded backup; the previous data is in ${kept}` : 'restored a downloaded backup';
}
